/* Test the card's real ctx.ws path without constructing a DOM. */
import assert from 'node:assert/strict';
globalThis.HTMLElement = class {};
globalThis.customElements = {get() {}, define() {}};
globalThis.window = {customCards: []};
const {AppHubCard} = await import('../custom_components/app_hub/www/app-hub-card.js');
const calls = [];
const card = Object.create(AppHubCard.prototype);
card._hass = {callWS: async (payload) => { calls.push(payload); return {ok: true}; }};
card._cfg = {dry_run: true};
card._backShown = () => false;
card._t = (key) => key;
const ctx = card._ctx();
assert.equal(typeof ctx.ws, 'function');
await ctx.ws('hue_studio/scene_get', {scene_id: 's'});
assert.deepEqual(calls.pop(), {type: 'hue_studio/scene_get', scene_id: 's'});
await ctx.ws('hue_studio/powerup', {light_id: 'l', preset: 'safety', dry_run: false, type: 'evil', id: 999});
assert.deepEqual(calls.pop(), {type: 'hue_studio/powerup', light_id: 'l', preset: 'safety', dry_run: true});
await assert.rejects(ctx.ws('hue_studio/zigbee_search'), /no dry_run contract/);
await assert.rejects(ctx.ws('other/write'), /no dry_run contract/);
const rd = {domain: 'shipment_tracking', service: 'inpost_query', service_data: {what: 'friends'}, return_response: true};
await ctx.ws('call_service', rd);
assert.deepEqual(calls.pop(), {type: 'call_service', ...rd});
await assert.rejects(ctx.ws('call_service', {...rd, service: 'inpost_locker'}), /no dry_run contract/);
await assert.rejects(ctx.ws('call_service', {...rd, domain: 'light', service: 'inpost_query'}), /no dry_run contract/);
assert.equal(calls.length, 0);
card._cfg = {dry_run: false};
await ctx.ws('other/write', {value: 7});
assert.deepEqual(calls.pop(), {type: 'other/write', value: 7});
card._hass = null;
await assert.rejects(ctx.ws('hue_studio/state'), /unavailable/);
console.log('ctx.ws OK: reads, write preview, payload protection, unknown-write rejection, normal calls, no connection');
